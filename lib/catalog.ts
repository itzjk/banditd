const SEPARATORS = /[^a-z0-9]+/g;

function flatten(value: string): string {
  return value.toLowerCase().replace(SEPARATORS, " ").trim();
}

function tolerance(word: string): number {
  if (word.length < 4) return 0;
  if (word.length <= 6) return 1;
  return 2;
}

function distance(a: string, b: string, max: number): number {
  if (a === b) return 0;
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  let row = new Array<number>(b.length + 1);
  for (let i = 1; i <= a.length; i += 1) {
    row[0] = i;
    let best = row[0];
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      row[j] = Math.min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + cost);
      if (row[j] < best) best = row[j];
    }
    if (best > max) return max + 1;
    const spare = prev;
    prev = row;
    row = spare;
  }
  return prev[b.length];
}

function wordRank(token: string, word: string): number {
  if (word === token) return 0;
  if (word.startsWith(token)) return 1;
  if (word.includes(token)) return 2;
  const max = tolerance(token);
  if (max === 0) return -1;
  if (distance(token, word, max) <= max) return 3;
  if (word.length > token.length && distance(token, word.slice(0, token.length), max) <= max) {
    return 4;
  }
  return -1;
}

function rank(
  name: string,
  query: string,
  tokens: string[],
): { tier: number; penalty: number } | null {
  const flat = flatten(name);
  if (flat.startsWith(query)) return { tier: 0, penalty: 0 };
  const at = flat.indexOf(query);
  if (at > 0) return { tier: flat[at - 1] === " " ? 1 : 2, penalty: at };
  const pool = flat.split(" ");
  let matched = 0;
  let solid = 0;
  let penalty = 0;
  for (const token of tokens) {
    let best = -1;
    for (const word of pool) {
      const score = wordRank(token, word);
      if (score >= 0 && (best < 0 || score < best)) best = score;
    }
    if (best < 0) continue;
    matched += 1;
    penalty += best;
    if (best <= 3 && token.length >= 4) solid += 1;
  }
  if (matched === 0 || matched * 2 < tokens.length) return null;
  const missed = tokens.length - matched;
  if (missed > 0 && solid === 0) return null;
  return { tier: 3 + missed, penalty };
}

export function searchCatalog(input: string, limit = 6): CatalogProduct[] {
  const query = flatten(input);
  if (query.length < 2) return [];
  const tokens = query.split(" ");
  const hits: { item: CatalogProduct; tier: number; penalty: number; order: number }[] = [];
  for (let i = 0; i < CATALOG.length; i += 1) {
    const item = CATALOG[i];
    const scored = rank(item.name, query, tokens);
    if (!scored) continue;
    hits.push({ item, tier: scored.tier, penalty: scored.penalty, order: i });
  }
  hits.sort((a, b) => a.tier - b.tier || a.penalty - b.penalty || a.order - b.order);
  return hits.slice(0, limit).map((hit) => hit.item);
}
